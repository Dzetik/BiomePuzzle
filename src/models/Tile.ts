// ============================================================================
// МОДЕЛЬ ПЛИТКИ
// ============================================================================
// Хранит состояние отдельной плитки: ID, текстуру, поворот, цвета рёбер.
// baseEdges вычисляется из tileDefinitions если не передан явно — это позволяет
// создавать копии плиток только по id + textureKey + rotation.
// ============================================================================

import { Edge, Rotation, Color, EdgeColors, TileData } from './Tile.types';
import { TILE_DEFINITIONS } from '../data/tileDefinitions';

// ============================================================================
// ВСПОМОГАТЕЛЬНАЯ ФУНКЦИЯ: ПОЛУЧЕНИЕ БАЗОВЫХ РЁБЕР ПО TEXTUREKEY
// ============================================================================
// Ищет определение плитки в TILE_DEFINITIONS и возвращает baseEdges.
// Если не найдено — возвращает дефолтные серые рёбра.
// ============================================================================
const getBaseEdgesFromTextureKey = (textureKey: string): EdgeColors => {
  const definition = TILE_DEFINITIONS.find(def => def.textureKey === textureKey);
  
  if (definition?.baseEdges) {
    return definition.baseEdges;
  }
  
  // Дефолтные рёбра если текстура не найдена
  return { top: 'gray', right: 'gray', bottom: 'gray', left: 'gray' };
};

// ============================================================================
// КЛАСС ПЛИТКИ
// ============================================================================
export class Tile {
  public readonly id: string;
  public readonly textureKey: string;
  
  private _rotation: Rotation = 0;
  private _baseEdges: EdgeColors;

  // ============================================================================
  // КОНСТРУКТОР
  // ============================================================================
  // Принимает TileData + опциональный rotation.
  // Если baseEdges не передан — вычисляется из TILE_DEFINITIONS по textureKey.
  // ============================================================================
  constructor(data: TileData & { rotation?: Rotation }) {
    this.id = data.id;
    this.textureKey = data.textureKey;
    
    // Вычисляем baseEdges из TILE_DEFINITIONS если не передан явно
    this._baseEdges = data.baseEdges ?? getBaseEdgesFromTextureKey(data.textureKey);
    
    // Сохраняем rotation с приведением типа к Rotation (0 | 90 | 180 | 270)
    this._rotation = (data.rotation ?? 0) as Rotation;
  }

  // ============================================================================
  // ГЕТТЕР: ТЕКУЩИЙ УГОЛ ПОВОРОТА
  // ============================================================================
  public get rotation(): Rotation {
    return this._rotation;
  }

  // ============================================================================
  // СЕТТЕР: УСТАНОВКА УГЛА ПОВОРОТА
  // ============================================================================
  public setRotation(rotation: Rotation): void {
    this._rotation = rotation;
  }

  // ============================================================================
  // ГЕТТЕР: ЦВЕТА РЁБЕР С УЧЁТОМ ПОВОРОТА
  // ============================================================================
  // Вычисляет актуальные цвета рёбер на основе _baseEdges и _rotation.
  // Не мутирует объект, возвращает новое вычисленное значение.
  // Поворот по часовой стрелке: 90° = сдвиг на 1 позицию вправо.
  // ============================================================================
  public get currentEdges(): EdgeColors {
    const edges: Edge[] = ['top', 'right', 'bottom', 'left'];
    const steps = this._rotation / 90;  // 0, 1, 2, или 3
    
    const result: Partial<EdgeColors> = {};

    edges.forEach((edge, index) => {
      // Вычисляем индекс базового ребра с учётом поворота
      // Формула: (текущий индекс - шаги поворота + 4) % 4
      // +4 нужен чтобы избежать отрицательных индексов
      const baseIndex = (index - steps + 4) % 4;
      const baseEdge = edges[baseIndex];
      
      result[edge] = this._baseEdges[baseEdge as Edge];
    });

    return result as EdgeColors;
  }

  // ============================================================================
  // МЕТОД: ПОВОРОТ НА 90° ПО ЧАСОВОЙ СТРЕЛКЕ
  // ============================================================================
  // Циклически переключает: 0 → 90 → 180 → 270 → 0
  // ============================================================================
  public rotate(): void {
    this._rotation = ((this._rotation + 90) % 360) as Rotation;
  }

  // ============================================================================
  // МЕТОД: СБРОС ПОВОРОТА В 0
  // ============================================================================
  // Используется при возврате плитки в спавнер или при необходимости
  // сбросить визуальное состояние.
  // ============================================================================
  public resetRotation(): void {
    this._rotation = 0;
  }

  // ============================================================================
  // МЕТОД: ПОЛУЧЕНИЕ ЦВЕТА КОНКРЕТНОГО РЕБРА
  // ============================================================================
  // Удобный хелпер для получения цвета одного ребра с учётом поворота.
  // ============================================================================
  public getEdgeColor(edge: Edge): Color {
    return this.currentEdges[edge];
  }
}